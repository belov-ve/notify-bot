#!/bin/bash
# Скрипт получения статистики очередей бота

PORT="${HEALTH_CHECK_PORT:-8040}"
URL="http://localhost:$PORT/stats"

# Выполняем GET-запрос к эндпоинту статистики с таймаутом 10 секунд
RESPONSE=$(curl -s -m 10 "$URL")

# Если запрос не удался (код завершения не 0 или ответ пустой), возвращаем ошибку
if [ $? -ne 0 ] || [ -z "$RESPONSE" ]; then
    echo "Ошибка: Не удалось получить статистику от бота по адресу $URL" >&2
    exit 1
fi

# Выводим JSON-ответ
echo "$RESPONSE"
